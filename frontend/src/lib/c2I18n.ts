export function getStoredC2Lang(): C2Lang {
  try {
    const current = localStorage.getItem(STORAGE_KEY);
    const legacy = current ? null : localStorage.getItem(LEGACY_STORAGE_KEY);
    const saved = current || legacy;
    if (saved === 'en' || saved === 'es') {
      if (!current) {
        localStorage.setItem(STORAGE_KEY, saved);
      }
      return saved;
    }
  } catch {
    // ignore storage errors
  }
  return 'es';
}

export function setStoredC2Lang(lang: C2Lang): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // ignore storage errors
  }
}

export function tC2(
  lang: C2Lang,
  key: string,
  vars?: Record<string, string | number | boolean | null | undefined>
): string {
  const table = STR[lang] || STR.en;
  let value = table[key] ?? STR.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.split(`{${k}}`).join(String(v ?? ''));
    }
  }
  return value;
}
